def test_store_turns_are_untouched_and_no_stub_aliases_a_stored_block():
    thread = _thread()
    _user(thread, "one")
    _tool_use(thread, ("tu_1", "get_holdings"))
    result_turn = _result(thread, "get_holdings", HOLDINGS_OK)
    _assistant(thread, "ok")
    _user(thread, "two")

    snapshot = [json.dumps(t.content) for t in thread.turns]
    view = curation.messages_for_model(thread)

    assert [json.dumps(t.content) for t in thread.turns] == snapshot
    assert result_turn.content[0]["content"] == json.dumps(
        HOLDINGS_OK, sort_keys=True, separators=(",", ":")
    )

    stored_ids = {id(block) for turn in thread.turns for block in turn.content}
    view_ids = {id(block) for message in view for block in message["content"]}
    stubbed = [
        b
        for message in view
        for b in message["content"]
        if isinstance(b.get("content"), str) and "result cleared" in b["content"]
    ]
    assert len(stubbed) == 1
    assert id(stubbed[0]) not in stored_ids

    # mutating the view can never reach the store or the memo cache
    stubbed[0]["content"] = "TAMPERED"
    assert [json.dumps(t.content) for t in thread.turns] == snapshot
    again = curation.messages_for_model(thread)
    assert "TAMPERED" not in json.dumps(again)
    assert view_ids  # sanity: the view really did carry blocks


