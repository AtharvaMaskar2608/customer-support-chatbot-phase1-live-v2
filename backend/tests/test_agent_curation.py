"""Read-time context curation (CHO-271 · tasks 4.1-4.14, 4.16).

Everything here is pure: threads are built through the real `ThreadStore`
(memory-only, so content/meta are canonicalized exactly as in production) and
no model, DB or clock is involved. The properties under test are the ones the
whole scheme rests on — the `tool_use`/`tool_result` pairing survives, the
watermark is monotone and within-turn stable, the store is never mutated, and
no renderer can physically read a currency amount.
"""

import json
