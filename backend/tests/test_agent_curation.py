STORE = ThreadStore(pool=None)  # memory-only: canonicalizes, never persists

FRAME = "[App note — generated by the app, not typed by the user]"


# --- thread builders ----------------------------------------------------------


def _thread() -> Thread:
    return Thread(id="thread-1", session_id="session-1")


def _user(thread, text="hello"):
    return STORE.append_turn(
        thread, role="user", kind="user_text",
        content=[{"type": "text", "text": text}],
    )


def _assistant(thread, text="here you go"):
    return STORE.append_turn(
        thread, role="assistant", kind="assistant_text",
        content=[{"type": "text", "text": text}],
    )


def _tool_use(thread, *uses):
    """uses: (tool_use_id, name) pairs — one assistant_tool_use turn."""
    return STORE.append_turn(
        thread, role="assistant", kind="assistant_tool_use",
        content=[
            {"type": "tool_use", "id": uid, "name": name, "input": {}}
            for uid, name in uses
        ],
    )


def _result(
    thread, tool, envelope=None, *, raw=None, is_error=False, tool_use_id="tu_1"
):
    content = (
        raw
        if raw is not None
        else json.dumps(envelope or {}, sort_keys=True, separators=(",", ":"))
    )
    return STORE.append_turn(
        thread, role="user", kind="tool_result",
        content=[
            {
                "type": "tool_result",
                "tool_use_id": tool_use_id,
                "content": content,
                "is_error": is_error,
            }
        ],
        meta={"tool_name": tool, "is_error": is_error, "duration_ms": 4},
    )


def _flow_event(thread, text="[App event] something happened."):
    return STORE.append_turn(
        thread, role="user", kind="flow_event",
        content=[{"type": "text", "text": text}],
    )


def _stub_text(turn):
    blocks = curation.stub_blocks(turn)
    assert blocks is not None, "expected this turn to be curatable"
    return blocks[0]["content"]


def _region_json(thread, *, upto_seq):
    """Serialize the curated projection restricted to turns with seq <=
    upto_seq, using the CURRENT watermark's transform. The head thread shares
    the real thread's memo dict through the closure."""
    transform = curation.curate(thread)
    head = Thread(id=thread.id, session_id=thread.session_id)
    head.turns = [t for t in thread.turns if t.seq <= upto_seq]
    return json.dumps(head.messages(transform=transform), separators=(",", ":"))


