def test_every_renderer_ends_with_an_actionable_recovery_clause():
    """Task 1.9 / the single most important design property: a stub must never
    read as a bare absence claim — that wording is what INDUCES abstention."""
    cases = [(tool, env) for tool, env, _ in GOLDEN]
    cases += [
        ("get_brokerage_rates", {"kind": "empty"}),
        ("search_knowledge_base", {"kind": "ok", "results": []}),
        ("list_contract_notes", _notes(6)),
        ("list_contract_notes", _notes(45)),
        ("download_contract_note", FILE_EMAIL),
    ]
    for tool, envelope in cases:
        thread = _thread()
        _user(thread)
        text = _stub_text(_result(thread, tool, envelope))
        assert text.endswith("."), (tool, text)
        # names a tool to call again, in the final sentence
        last = text.rsplit(". ", 1)[-1]
        assert re.search(r"\bcall \w+\b", last, re.IGNORECASE), (tool, last)


