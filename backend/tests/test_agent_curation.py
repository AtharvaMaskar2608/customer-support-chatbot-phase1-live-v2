# --- 4.13 the key whitelist IS the currency guard ----------------------------

# Anything amount-, price-, identity-, token- or label-bearing that a stub must
# never be able to read. The guard is structural: these keys are absent from
# every whitelist, so no renderer can reach them even by mistake.
FORBIDDEN_KEYS = frozenset(
    {
        "amt", "landed", "counts", "totalRecords", "current", "invested",
        "pnl", "pnlPct", "day", "dayPct", "alloc", "ltp", "LTP", "abp", "ABP",
        "CP", "Q", "Sym", "Name", "rates", "desc", "title", "label", "gloss",
        "answer", "tat", "score", "fileToken", "emailMasked", "sizeLabel",
        "asOf", "badge", "month", "ambiguousLabels", "note", "seed",
        "prefilled", "st", "dt", "dest", "ref", "rsn", "mode", "rows", "list",
        "ticketId", "expiresAt", "ttlSeconds", "passwordProtected",
    }
)

# Count / length / customer-facing-label / date / id keys only.
ALLOWED_VOCABULARY = frozenset(
    {
        "kind", "totals", "count", "txns", "partial", "groups", "delivery",
        "file", "name", "results", "question", "report", "columns", "notes",
        "id", "date", "segment",
    }
)


def test_every_renderer_has_a_whitelist_and_vice_versa():
    assert set(curation._RENDERERS) == set(curation._ALLOWED_KEYS)


def test_no_whitelist_contains_an_amount_bearing_key():
    for tool, allowed in curation._ALLOWED_KEYS.items():
        assert not (allowed & FORBIDDEN_KEYS), (tool, allowed & FORBIDDEN_KEYS)
        assert allowed <= ALLOWED_VOCABULARY, (tool, allowed - ALLOWED_VOCABULARY)


def _keys_at_every_depth(value):
    if isinstance(value, dict):
        out = set(value)
        for item in value.values():
            out |= _keys_at_every_depth(item)
        return out
    if isinstance(value, list):
        out = set()
        for item in value:
            out |= _keys_at_every_depth(item)
        return out
    return set()


@pytest.mark.parametrize(
    "tool,envelope",
    [
        ("get_holdings", HOLDINGS_OK),
        ("get_money_transactions", MONEY_OK),
        ("get_brokerage_rates", BROKERAGE_OK),
        ("get_pnl_report", FILE_DOWNLOAD),
        ("get_ledger_report", FILE_EMAIL),
        ("download_contract_note", NOTE_DOWNLOAD),
        ("search_knowledge_base", KB_OK),
        ("get_report_columns", COLUMNS_OK),
        ("list_contract_notes", _notes(20)),
    ],
)
def test_pruned_view_carries_no_forbidden_key(tool, envelope):
    view = curation._prune(envelope, curation._ALLOWED_KEYS[tool])
    assert not (_keys_at_every_depth(view) & FORBIDDEN_KEYS)
    assert _keys_at_every_depth(view) <= ALLOWED_VOCABULARY


